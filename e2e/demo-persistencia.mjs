import { as, go, errors, browser } from "./common.mjs";
const out = [];
const check = (name, okv) => out.push(`${okv ? "PASA" : "FALLA"} · ${name}`);
const page = await as("laura");
await go(page, "/dashboard");
await page.getByRole("button", { name: "Abrir modo demostración" }).click();
await page.waitForTimeout(2000);
check("rótulo de demo visible", await page.getByText("Modo demostración — guardado en este navegador").isVisible());
await go(page, "/projects/p-1051?tab=billing");
await page.getByLabel("Número").fill("E2E-0001");
await page.getByLabel("Importe sin IVA").fill("123456");
await page.getByRole("button", { name: "Registrar factura" }).click();
await page.waitForTimeout(800);
check("la factura aparece", await page.getByText("E2E-0001").first().isVisible());
await page.reload();
await page.waitForTimeout(2500);
await page.getByRole("tab", { name: "Facturación" }).click().catch(() => {});
await page.waitForTimeout(600);
check("después de recargar sigue la factura", await page.getByText("E2E-0001").first().isVisible());
// Otra sesión ve el mismo estado: Compras no ve facturas, pero Gerencia en el dashboard sí la suma.
await go(page, "/dashboard");
await page.getByText("Facturación y cobros").click();
await page.waitForTimeout(500);
check("el dashboard incluye la OT con lo facturado", (await page.locator("#facturacion").innerText()).includes("P-1051"));
await page.getByRole("button", { name: "Restaurar datos de prueba" }).first().click();
await page.getByRole("dialog").getByRole("button", { name: "Restaurar datos de prueba" }).click();
await page.waitForTimeout(800);
await go(page, "/projects/p-1051?tab=billing");
check("restaurar quita la factura", (await page.getByText("E2E-0001").count()) === 0);
await page.getByRole("button", { name: "Salir de la demostración" }).click();
await page.waitForTimeout(3000);
check("al salir no queda el rótulo de demo", (await page.getByText("Modo demostración — guardado en este navegador").count()) === 0);
console.log(out.join("\n"));
console.log(errors.length ? "Errores:\n" + errors.join("\n") : "sin errores de consola");
await browser.close();
